// Precompute responsive assets so image requests stay on the static CDN.
const fs=require('node:fs/promises');
const path=require('node:path');
const {createHash}=require('node:crypto');
const sharp=require('sharp');
const root=path.resolve(__dirname,'../..'),publicDir=path.join(root,'public');
const outputDir=path.join(publicDir,'img/optimized');
const cacheDir=path.join(root,'.next/cache/responsive-images');
const manifestFile=path.join(root,'src/data/image-assets.json');
const recipe='responsive-webp-v1';
sharp.concurrency(1);

async function sources(dir){
  const files=[];
  for(const entry of await fs.readdir(dir,{withFileTypes:true})){
    const file=path.join(dir,entry.name);
    if(file===outputDir)continue;
    if(entry.isDirectory())files.push(...await sources(file));
    else if(/\.(png|jpe?g|webp|svg)$/i.test(entry.name))files.push(file);
  }
  return files.sort();
}
function widthsFor(src,width){
  const sizes=/^\/img\/scoreline\/(flags|teams)\//.test(src)?[64,128,256,512]
    :/\/(players|portraits)\//.test(src)?[64,128,256,384,512]
    :/\/(country|countries|flags|clubs|teams|tournaments|icons)\//.test(src)?[32,64,128,256]
    :[160,320,640,960,1280,1920];
  return [...new Set(sizes.map(size=>Math.min(size,width)))].sort((a,b)=>a-b);
}
async function exists(file){try{await fs.access(file);return true;}catch{return false;}}
async function cached(output){
  const cache=path.join(cacheDir,path.basename(output));
  if(await exists(output)){if(!await exists(cache))await fs.copyFile(output,cache);return true;}
  if(await exists(cache)){await fs.copyFile(cache,output);return true;}
  return false;
}
async function store(output,buffer){
  await fs.writeFile(output,buffer);
  await fs.copyFile(output,path.join(cacheDir,path.basename(output)));
}
async function writeIfChanged(file,value){
  if(await fs.readFile(file,'utf8').catch(()=>null)===value)return;
  await fs.mkdir(path.dirname(file),{recursive:true});
  await fs.writeFile(file+'.tmp',value);await fs.rename(file+'.tmp',file);
}

async function main(){
  const started=Date.now(),files=await sources(publicDir),entries=new Map();
  await fs.mkdir(outputDir,{recursive:true});
  await fs.mkdir(cacheDir,{recursive:true});
  let cursor=0,created=0,originalBytes=0,representativeBytes=0;
  const generated=new Map();
  async function build(file){
    const src='/'+path.relative(publicDir,file).split(path.sep).join('/');
    const buffer=await fs.readFile(file),svg=file.toLowerCase().endsWith('.svg');
    const quality=/logo|title|branding/.test(src)?90:82;
    const metadata=svg?null:await sharp(buffer).metadata();
    if(metadata?.pages>1)return; // Preserve animation rather than taking one frame.
    const width=metadata&&[5,6,7,8].includes(metadata.orientation)?metadata.height:metadata?.width;
    const widths=svg?[]:widthsFor(src,width);
    const id=createHash('sha256').update(buffer).update(JSON.stringify({recipe,widths,quality})).digest('hex').slice(0,20);
    entries.set(src,[id,widths]);originalBytes+=buffer.length;
    if(!generated.has(id))generated.set(id,(async()=>{
      if(svg){const output=path.join(outputDir,id+'.svg');if(!await cached(output)){await store(output,buffer);created++;}return;}
      for(const size of widths){
        const output=path.join(outputDir,`${id}-${size}.webp`);
        if(await cached(output))continue;
        let result=await sharp(buffer).rotate().resize({width:size,withoutEnlargement:true}).webp({quality,alphaQuality:100,effort:4,smartSubsample:true}).toBuffer();
        if(metadata.format==='webp'&&size===width&&result.length>buffer.length)result=buffer;
        await store(output,result);created++;
      }
    })());
    await generated.get(id);
    const size=widths.find(size=>size>=256)||widths.at(-1);
    const stat=await fs.stat(path.join(outputDir,svg?id+'.svg':`${id}-${size}.webp`));
    representativeBytes+=stat.size;
  }
  await Promise.all(Array.from({length:4},async()=>{while(cursor<files.length)await build(files[cursor++]);}));
  const manifest=Object.fromEntries([...entries].sort(([a],[b])=>a.localeCompare(b)));
  await writeIfChanged(manifestFile,JSON.stringify(manifest)+'\n');
  const backgrounds={
    'stadium':'/img/hero/stadium.webp',
    'higher-lower-burst':'/img/higher-lower/player-burst.png',
    'journey-stadium':'/img/journeyman/stadium-timeline.webp',
    'matrix-stadium':'/img/matrix/stadium-board.webp',
  };
  const asset=(src,width)=>{const [id,sizes]=manifest[src];const size=sizes.find(size=>size>=width)||sizes.at(-1);return `/img/optimized/${id}-${size}.webp`;};
  const css='/* Generated by scripts/images/build.cjs. */\n:root{\n'+Object.entries(backgrounds).map(([name,src])=>`  --image-${name}:image-set(url("${asset(src,960)}") 1x,url("${asset(src,1920)}") 2x);`).join('\n')+'\n}\n';
  await writeIfChanged(path.join(root,'src/app/image-assets.css'),css);
  console.log(`Images: ${entries.size} sources, ${created} new variants, ${((Date.now()-started)/1000).toFixed(1)}s. Representative card assets: ${(originalBytes/1048576).toFixed(1)} MB → ${(representativeBytes/1048576).toFixed(1)} MB.`);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
